def load_product_catalog() -> list[dict]:
    """Prodotti reali con le rispettive garanzie dalla matrice prodotti.

    Output: [{code, description, guarantees: [{code, description, coverage_area}]}].
    Lista vuota se il file non esiste (fallback ai PRODUCTS legacy senza garanzie).
    """
    try:
        with open(MATRICE_PATH, encoding="utf-8") as f:
            payload = json.load(f)
    except OSError:
        return []
    by_product: dict[str, dict] = {}
    for e in payload.get("entries", []):
        prod = by_product.setdefault(e["product_code"], {
            "code": e["product_code"],
            "description": e.get("product_description") or e["product_code"],
            "guarantees": [],
        })
        prod["guarantees"].append({
            "code": e.get("guarantee_code"),
            "description": e.get("guarantee_description"),
            "coverage_area": e.get("coverage_area"),
        })
    return list(by_product.values())


PRODUCT_CATALOG = load_product_catalog()


def iso(d: date) -> str:
    return d.isoformat()


def today() -> date:
    return date.today()


def rand_phone(rng: random.Random) -> str:
    return "333" + "".join(str(rng.randint(0, 9)) for _ in range(7))


def rand_email(rng: random.Random, i: int) -> str:
    return f"cliente{i}@email.it"


def rand_future_date(rng: random.Random, min_days: int, max_days: int) -> date:
    return today() + timedelta(days=rng.randint(min_days, max_days))


def rand_past_date(rng: random.Random, min_days: int, max_days: int) -> date:
    return today() - timedelta(days=rng.randint(min_days, max_days))


def maybe(rng: random.Random, value_fn, p: float = 0.5):
    return value_fn() if rng.random() < p else None


def gen_policies(rng: random.Random, client_idx: int) -> list[dict]:
    n = rng.randint(1, 3)
    out = []
    for j in range(n):
        policy = {
            "policy_number": f"P{client_idx:03d}{j}{rng.randint(100,999)}",
            "premium": rng.randint(250, 2600),
            "expiry_date": iso(rand_future_date(rng, 0, 365)),
            "churn_rate": round(rng.random() * 0.95, 2),
        }
        if PRODUCT_CATALOG:
            prod = rng.choice(PRODUCT_CATALOG)
            k = min(len(prod["guarantees"]), rng.randint(1, 4))
            policy["product"] = prod["description"]
            policy["product_code"] = prod["code"]
            policy["guarantees"] = rng.sample(prod["guarantees"], k=k)
        else:
            policy["product"] = rng.choice(PRODUCTS)
            policy["guarantees"] = []
        out.append(policy)
    return out


def gen_insurance_needs(rng: random.Random) -> list[dict] | None:
    """Checkup assicurativo sintetico in forma compatta v4 (insurance_needs_balanced_v1)."""
    if rng.random() < 0.40:
        return None  # checkup non fatto
    need_keys = rng.sample(list(NEEDS_CATALOG), k=rng.randint(3, len(NEEDS_CATALOG)))
    needs = {}
    for need_key in need_keys:
        spec = NEEDS_CATALOG[need_key]
        events = {}
        for ev_key, area in spec["events"].items():
            events[ev_key] = {
                "selected": False,
                "necessary": bool(rng.random() < 0.55),
                "activeWithVittoria": False,
                "area": area,
            }
        needs[need_key] = {"typeId": spec["typeId"], "events": events}
    return [{
        "schema": "insurance_needs_balanced_v1",
        "sourceVersion": "v4",
        "normalizedToV4BeforeCompaction": True,
        "needs": needs,
    }]


def gen_cases(rng: random.Random, kind: str) -> list[dict] | None:
    # kind: CLAIM or COMPLAINT
    if rng.random() < 0.65:
        return None
    n = rng.randint(1, 2)
    out = []
    for _ in range(n):
        status = rng.choices(CASE_STATUS, weights=[0.45, 0.25, 0.30], k=1)[0]
        opened = rand_past_date(rng, 1, 120)
        out.append({
            "status": status,
            "opened_date": iso(opened),
            "reference_id": f"{kind[:1]}-{rng.randint(100000,999999)}",
        })
    return out


def gen_campaigns(rng: random.Random) -> list[dict] | None:
    if rng.random() < 0.70:
        return None
    n = rng.randint(1, 2)
    out = []
    for _ in range(n):
        prod = rng.choice(["CASA", "AUTO", "VITA", "PET"])
        end = rand_future_date(rng, 5, 90)
        out.append({
            "campaign_id": f"CAMP{rng.randint(100,999)}",
            "name": rng.choice([
                "Campagna Casa Primavera",
                "Promo Auto Sicura",
                "Vita Family",
                "Pet Care",
                "Sconto Multi-prodotto",
            ]),
            "product_scope": prod,
            "end_date": iso(end),
        })
    return out


def gen_pending_quotes(rng: random.Random) -> list[dict] | None:
    if rng.random() < 0.70:
        return None
    n = rng.randint(1, 2)
    out = []
    for _ in range(n):
        saved_at = rand_past_date(rng, 1, 30)
        start = rand_future_date(rng, 3, 40)
        out.append({
            "quote_id": f"Q{rng.randint(1000,9999)}",
            "product": rng.choice(["CASA", "AUTO", "VITA", "PET"]),
            "saved_at": iso(saved_at),
            "coverage_start_date": iso(start),
            "status": rng.choice(["PENDING", "DRAFT", "SAVED"]),
        })
    return out


def gen_client(rng: random.Random, i: int) -> dict:
    phone = maybe(rng, lambda: rand_phone(rng), p=0.88)
    email = maybe(rng, lambda: rand_email(rng, i), p=0.92)

    pref = rng.choice(CHANNELS)
    whatsapp_enabled = None
    if pref == "WHATSAPP" or rng.random() < 0.20:
        whatsapp_enabled = bool(rng.random() < 0.70)

    policies = gen_policies(rng, i)

    unpaid_days = []
    if rng.random() < 0.25:
        unpaid_days = [rng.randint(10, 60)]

    # checkup assicurativo: se presente, il motore deriva i gap dagli insurance_needs
    insurance_needs = gen_insurance_needs(rng)

    # cross sell gaps legacy (0..3) — solo per i clienti senza checkup
    gaps = [] if insurance_needs else rng.sample(GAP_KEYS, k=rng.randint(0, 3))

    # engagement
    viva_points = maybe(rng, lambda: rng.randint(0, 2500), p=0.65)
    viva_points_expiring = None
    if rng.random() < 0.20:
        viva_points_expiring = rng.randint(50, 800)

    viva_enrolled = maybe(rng, lambda: bool(rng.random() < 0.75), p=0.60)
    checkup_done = True if insurance_needs else maybe(rng, lambda: False, p=0.60)

    # relationship
    last_contact_days = maybe(rng, lambda: rng.randint(0, 180), p=0.75)
    birthday_days = maybe(rng, lambda: rng.randint(0, 7), p=0.25)
    anniversary_days = maybe(rng, lambda: rng.randint(0, 30), p=0.20)

    # value drivers
    tenure_years = maybe(rng, lambda: round(rng.random() * 25, 1), p=0.70)
    active_policies_count = maybe(rng, lambda: len(policies), p=0.85)
    agency_profitability = maybe(rng, lambda: round(rng.random() * 2000, 0), p=0.55)
    company_sp = maybe(rng, lambda: round(rng.random() * 1.2, 2), p=0.55)  # 0..1.2
    auto_norm = maybe(rng, lambda: round(rng.random() * 2000, 0), p=0.55)
    auto_vct = maybe(rng, lambda: round(0.6 + rng.random() * 0.8, 2), p=0.45)  # 0.6..1.4
    non_auto_prem = maybe(rng, lambda: round(rng.random() * 5000, 0), p=0.60)

    claims = gen_cases(rng, "CLAIM")
    complaints = gen_cases(rng, "COMPLAINT")

    campaigns = gen_campaigns(rng)
    pending_quotes = gen_pending_quotes(rng)

    return {
        "client_id": f"C{i:03d}",
        "email": email,
        "phone": phone,
        "preferred_channel": pref,
        "whatsapp_enabled": whatsapp_enabled,

        "last_contact_days": last_contact_days,
        "birthday_days": birthday_days,
        "anniversary_days": anniversary_days,

        "unpaid_days": unpaid_days,
        "cross_sell_gaps": gaps,
        "policies": policies,
        "insurance_needs": insurance_needs,

        "viva_points": viva_points,
        "viva_points_expiring": viva_points_expiring,
        "viva_enrolled": viva_enrolled,
        "checkup_done": checkup_done,

        "claims": claims,
        "complaints": complaints,

        "active_campaigns": campaigns,
        "pending_quotes": pending_quotes,

        "customer_tenure_years": tenure_years,
        "active_policies_count": active_policies_count,
        "agency_profitability": agency_profitability,
        "company_profitability_sp": company_sp,
        "auto_premium_normalized": auto_norm,
        "auto_guarantees_weight_vct": auto_vct,
        "non_auto_premium_total": non_auto_prem,
    }


def gen_lead(rng: random.Random, i: int) -> dict:
    phone = maybe(rng, lambda: rand_phone(rng), p=0.85)
    email = maybe(rng, lambda: f"lead{i}@email.it", p=0.70)
    pref = rng.choice(CHANNELS)
    whatsapp_enabled = None
    if pref == "WHATSAPP" or rng.random() < 0.15:
        whatsapp_enabled = bool(rng.random() < 0.60)

    return {
        "lead_id": f"L{i:03d}",
        "product": rng.choice(PRODUCTS),
        "created_hours_ago": rng.randint(1, 96),
        "last_contact_days": maybe(rng, lambda: rng.randint(0, 10), p=0.55),
        "quote_premium": maybe(rng, lambda: rng.randint(200, 900), p=0.65),
        "coverage_start_days": maybe(rng, lambda: rng.randint(1, 30), p=0.55),
        "marketing_consent": bool(rng.random() < 0.90),

        "preferred_channel": pref,
        "whatsapp_enabled": whatsapp_enabled,
        "phone": phone,
        "email": email,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="dataset.json")
    ap.add_argument("--clients", type=int, default=50)
    ap.add_argument("--leads", type=int, default=20)
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    rng = random.Random(args.seed)

    clients = [gen_client(rng, i) for i in range(1, args.clients + 1)]
    leads = [gen_lead(rng, i) for i in range(1, args.leads + 1)]

    dataset = {"clients": clients, "leads": leads}
    with open(args.out, "w", encoding="utf-8") as f:
        json.dump(dataset, f, indent=2, ensure_ascii=False)

    print(f"OK: wrote {args.out} (clients={len(clients)}, leads={len(leads)})")


if __name__ == "__main__":
    main()
