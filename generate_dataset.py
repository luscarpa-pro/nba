CHANNELS = [None, "PHONE", "EMAIL", "SMS", "WHATSAPP"]

CASE_STATUS = ["OPEN", "IN_PROGRESS", "CLOSED"]

MATRICE_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "matrice_prodotti_garanzie.json")

